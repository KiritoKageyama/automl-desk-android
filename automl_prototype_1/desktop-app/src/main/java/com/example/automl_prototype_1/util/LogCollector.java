package com.example.automl_prototype_1.util;

import java.io.*;
import java.nio.file.*;
import java.util.zip.*;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;

public class LogCollector {

    public static String collectLogs() {
        String timestamp = LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyyMMdd_HHmmss"));
        String zipFileName = "automl_debug_logs_" + timestamp + ".zip";
        Path zipPath = Paths.get(zipFileName).toAbsolutePath();

        try (ZipOutputStream zos = new ZipOutputStream(new FileOutputStream(zipPath.toFile()))) {
            // Collect launch logs generated by run scripts
            addFileToZip(zos, "launch_log.txt");
            addFileToZip(zos, "launch_log_final.txt");
            addFileToZip(zos, "launch_log_optimized.txt");
            addFileToZip(zos, "launch_log_visible.txt");

            // Collect core logs if available (adjust path as needed)
            // System.out.println("Collecting logs...");

            System.out.println("Logs collected successfully to: " + zipPath);
            return zipPath.toString();
        } catch (IOException e) {
            com.example.automl_prototype_1.service.LogService.error("LogCollector",
                    "Failed to collect logs: " + e.getMessage());
            return null;
        }
    }

    private static void addFileToZip(ZipOutputStream zos, String fileName) throws IOException {
        Path file = Paths.get(fileName);
        if (Files.exists(file)) {
            zos.putNextEntry(new ZipEntry(fileName));
            Files.copy(file, zos);
            zos.closeEntry();
            System.out.println("Added: " + fileName);
        } else {
            System.out.println("Skipped (Not Found): " + fileName);
        }
    }

    public static void main(String[] args) {
        collectLogs();
    }
}
